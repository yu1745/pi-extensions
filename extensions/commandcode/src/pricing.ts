import {
  GENERATED_FREE_MODEL_IDS,
  GENERATED_MODEL_COSTS,
  GENERATED_UNPRICED_MODEL_IDS,
  PRICING_VERIFIED_ON,
} from "./pricing-table.generated.ts"

export interface CommandCodeModelCostRates {
  input: number
  output: number
  cacheRead: number
  cacheWrite: number
}

export interface CommandCodeModelCostTier extends CommandCodeModelCostRates {
  inputTokensAbove: number
}

export interface CommandCodeModelCost extends CommandCodeModelCostRates {
  tiers?: readonly CommandCodeModelCostTier[]
}

export interface TemporaryPricing {
  models: readonly string[]
  expiresOn: string
  description: string
}

export const PRICING_SOURCE_URL = "https://commandcode.ai/docs/resources/pricing-limits"

/** Day the generated table was last reconciled with upstream. */
export const PRICING_LAST_VERIFIED = PRICING_VERIFIED_ON

export const ZERO_MODEL_COST: CommandCodeModelCost = {
  input: 0,
  output: 0,
  cacheRead: 0,
  cacheWrite: 0,
}

/**
 * Models Command Code serves at no credit cost.
 *
 * Derived from the generated table's free list, so a model is free only because
 * the pricing page says so — never because a row of zeroes was typed here. Run
 * `pnpm pricing:sync` to refresh it.
 */
export const FREE_MODEL_IDS: ReadonlySet<string> = new Set(GENERATED_FREE_MODEL_IDS)

/**
 * Catalog ids upstream lists without a pricing row.
 *
 * They fall back to $0 at runtime and log a warning; the sync reports them so
 * the gap is visible instead of silent.
 */
export const UNPRICED_MODEL_IDS: ReadonlySet<string> = new Set(GENERATED_UNPRICED_MODEL_IDS)

/**
 * Display prices in USD per million tokens.
 *
 * Generated by `pnpm pricing:sync` (see `scripts/sync-pricing.mjs`) from the
 * pricing page's embedded payload mapped onto the live catalog. Tiered entries
 * use pi's request-wide input pricing: the highest threshold exceeded by
 * input + cache reads + cache writes applies to the full request. The Command
 * Code usage page remains authoritative for the amount billed for an
 * individual request.
 */
export const MODEL_COSTS: Readonly<Record<string, CommandCodeModelCost>> = GENERATED_MODEL_COSTS

/**
 * Hand-owned list of promotions whose rates differ from the generated table and
 * that therefore need review when they expire. Ordinary discounts are already
 * reflected in `MODEL_COSTS`, so they do not belong here.
 */
export const TEMPORARY_PRICING: readonly TemporaryPricing[] = []
